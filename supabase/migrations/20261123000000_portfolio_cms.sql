-- Private Portfolio 1.1 content-management tables.
create table if not exists public.cms_records (
  id uuid primary key default gen_random_uuid(),
  record_type text not null check (record_type in ('project','skill','experience','education','credential','achievement','article','profile','category')),
  record_key text not null,
  draft_version_id uuid,
  published_version_id uuid,
  publication_state text not null default 'draft' check (publication_state in ('draft','published','archived')),
  published_commit_sha text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null,
  updated_by uuid not null,
  unique (record_type, record_key)
);

create table if not exists public.cms_record_versions (
  id uuid primary key default gen_random_uuid(),
  record_id uuid not null references public.cms_records(id) on delete cascade,
  version_number integer not null,
  public_payload jsonb not null default '{}'::jsonb,
  editorial_metadata jsonb not null default '{}'::jsonb,
  change_summary text not null default '',
  created_at timestamptz not null default now(),
  created_by uuid not null,
  unique (record_id, version_number)
);

alter table public.cms_records
  add constraint cms_records_draft_version_fk
  foreign key (draft_version_id) references public.cms_record_versions(id) on delete set null;
alter table public.cms_records
  add constraint cms_records_published_version_fk
  foreign key (published_version_id) references public.cms_record_versions(id) on delete set null;

create table if not exists public.cms_publications (
  id uuid primary key default gen_random_uuid(),
  record_id uuid references public.cms_records(id) on delete set null,
  record_version_id uuid references public.cms_record_versions(id) on delete set null,
  status text not null check (status in ('prepared','checks_pending','checks_failed','ready_to_merge','merged','deployment_pending','live','failed','cancelled')),
  branch_name text,
  pull_request_number integer,
  head_sha text,
  merge_commit_sha text,
  workflow_run_id text,
  deployment_url text,
  failure_code text,
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid not null
);

create table if not exists public.cms_audit_events (
  id bigint generated by default as identity primary key,
  actor_user_id uuid not null,
  record_id uuid references public.cms_records(id) on delete set null,
  publication_id uuid references public.cms_publications(id) on delete set null,
  action text not null,
  version_id uuid references public.cms_record_versions(id) on delete set null,
  outcome text not null check (outcome in ('success','failure')),
  created_at timestamptz not null default now()
);

alter table public.cms_records enable row level security;
alter table public.cms_record_versions enable row level security;
alter table public.cms_publications enable row level security;
alter table public.cms_audit_events enable row level security;

revoke all on public.cms_records, public.cms_record_versions, public.cms_publications, public.cms_audit_events
  from anon, authenticated;

